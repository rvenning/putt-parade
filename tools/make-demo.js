// Records bot rounds on a few showcase holes into js/demo.js. The title screen
// replays them through the real engine, which is deterministic, so a shot
// fired at the recorded hole time lands exactly where it did here.
//   node tools/make-demo.js
const fs = require("fs"), path = require("path");
const E = require("../tests/load.js");
const PICK = ["meadow-9", "fair-4", "pier-8", "frost-3", "fair-3"];
const out = [];
for (const id of PICK) {
  const def = E.HOLES.find((h) => h.id === id), H = E.compileHole(def);
  let best = null;
  for (let seed = 1; seed <= 6 && !best; seed++) {
    const rnd = E.mulberry32(seed * 101), sim = new E.HoleSim(H, [{ id: "demo" }]), shots = [];
    for (let k = 0; k < 240 * 1.2; k++) sim.step();     // a beat before the first putt
    let guard = 0;
    while (!sim.over && guard++ < 8) {
      const b = sim.ball, pl = E.Bot.plan(H, b.x, b.y, sim.t, E.SKILLS.adult);
      const a = pl.a + (rnd() - 0.5) * 0.02, p = Math.min(1, pl.p * (1 + (rnd() - 0.5) * 0.04));
      shots.push({ t: sim.t, a, p });
      sim.shoot(a, p);
      while (sim.ball.state === "moving") sim.step();
      for (let k = 0; k < 240 * (1.3 + rnd()); k++) sim.step();
    }
    if (sim.balls[0].state === "in" && shots.length <= 3) best = shots;
  }
  if (best) out.push({ hole: id, shots: best });
  console.log(id, best ? best.length + " shots" : "skipped");
}
const src = `// Recorded demo rounds for the title screen — generated by tools/make-demo.js.
// Re-run it after changing any of these holes or the physics.
const DEMO = ${JSON.stringify(out)};
if (typeof module !== "undefined") module.exports = { DEMO };
`;
fs.writeFileSync(path.join(__dirname, "..", "js", "demo.js"), src);
